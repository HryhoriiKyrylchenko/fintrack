using FinTrack.Shared.Kernel.Monetary;
using FinTrack.Shared.Kernel.Time;

namespace FinTrack.Budget.Contracts.V1.Plans;

/// <summary>
/// Body of <c>POST /api/v1/plans/{id}/amount</c>: the plan's new monthly amount from <paramref name="From"/> on (a new version; plan
/// 1b B7). Answers 204. Earlier months keep what they accrued: a version from a month before the current one that would change
/// what that month accrued is refused (invariant 6). Repeats as for a deposit.
/// </summary>
/// <remarks>
/// Failures: 400 <c>money.amount_not_positive</c>, <c>plan.months_invalid</c> (<paramref name="From"/> before the plan's first month
/// or after its last), <c>validation.failed</c> (rule <c>RouteFormat</c> at <c>id</c>, or <c>JsonFormat</c>); 404
/// <c>plan.not_found</c>, <c>settings.not_found</c>; 422 <c>plan.ended</c>, <c>bucket.archived</c>, <c>bucket.currency_mismatch</c>,
/// <c>entry.date_in_future</c>, <c>plan.past_period_changed</c> (parameter <c>month</c>: the first month that would change,
/// <c>yyyy-MM</c>).
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client.</param>
/// <param name="Amount">The new monthly amount, strictly positive, in the plan's currency.</param>
/// <param name="From">The first month of the new amount.</param>
/// <param name="OccurredOn">The day the owner made the change; not after today.</param>
/// <param name="Note">Optional; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record ChangePlanAmountRequest(
    Guid Id,
    Money Amount,
    YearMonth From,
    DateOnly OccurredOn,
    string? Note = null,
    IReadOnlyList<string>? Tags = null);
