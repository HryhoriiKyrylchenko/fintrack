using FinTrack.Shared.Kernel.Time;

namespace FinTrack.Budget.Contracts.V1.Plans;

/// <summary>
/// Body of <c>POST /api/v1/plans/{id}/end</c>: the plan's new last month, or no end when <paramref name="ValidTo"/> is <c>null</c>
/// (plan 1b B7). Answers 204. The end stops new months, not the obligation: a shortfall stays until it is paid. Ending a plan as of
/// last month is allowed; an end that would remove or add a month before that is refused (invariant 6). Repeats as for a deposit.
/// </summary>
/// <remarks>
/// Failures: 400 <c>plan.months_invalid</c> (an end before the plan's first month), <c>validation.failed</c> (rule <c>RouteFormat</c>
/// at <c>id</c>, or <c>JsonFormat</c>); 404 <c>plan.not_found</c>, <c>settings.not_found</c>; 422 <c>bucket.archived</c>,
/// <c>entry.date_in_future</c>, <c>plan.past_period_changed</c> (parameter <c>month</c>, <c>yyyy-MM</c>).
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client.</param>
/// <param name="OccurredOn">The day the owner made the change; not after today.</param>
/// <param name="ValidTo">The last month that accrues, or <c>null</c> to remove the end.</param>
/// <param name="Note">Optional; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record SetPlanEndRequest(
    Guid Id,
    DateOnly OccurredOn,
    YearMonth? ValidTo = null,
    string? Note = null,
    IReadOnlyList<string>? Tags = null);
