using FinTrack.Shared.Kernel.Time;

namespace FinTrack.Budget.Contracts.V1.Plans;

/// <summary>
/// Body of <c>POST /api/v1/plans/{id}/pauses/{pauseId}</c>: new values for a pause of the plan, replacing its months and mode (plan 1b
/// B10). Answers 204. Resuming is a change that sets <paramref name="To"/> (to last month, to resume from this month). A change that
/// would change what a month before the current one accrued is refused (invariant 6). Repeats as for a deposit.
/// </summary>
/// <remarks>
/// Failures: 400 <c>plan.months_invalid</c>, <c>validation.failed</c> (rule <c>RouteFormat</c> at <c>id</c> or <c>pauseId</c>, or
/// <c>JsonFormat</c>); 404 <c>plan.not_found</c>, <c>plan.pause_not_found</c> (no such pause of this plan), <c>settings.not_found</c>;
/// 422 <c>plan.pause_overlaps</c>, <c>bucket.archived</c>, <c>entry.date_in_future</c>, <c>plan.past_period_changed</c> (parameter
/// <c>month</c>).
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client.</param>
/// <param name="From">The first paused month.</param>
/// <param name="Mode"><c>Shift</c> or <c>Skip</c>.</param>
/// <param name="OccurredOn">The day the owner made the change; not after today.</param>
/// <param name="To">The last paused month, or <c>null</c> to pause until changed.</param>
/// <param name="Note">Optional; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record ChangePlanPauseRequest(
    Guid Id,
    YearMonth From,
    PauseMode Mode,
    DateOnly OccurredOn,
    YearMonth? To = null,
    string? Note = null,
    IReadOnlyList<string>? Tags = null);
