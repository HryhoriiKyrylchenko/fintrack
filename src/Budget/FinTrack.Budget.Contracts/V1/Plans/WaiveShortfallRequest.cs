using FinTrack.Shared.Kernel.Monetary;

namespace FinTrack.Budget.Contracts.V1.Plans;

/// <summary>
/// Body of <c>POST /api/v1/plans/{id}/waivers</c>: part of the plan's shortfall written off, with its reason (plan 1b B11). Answers
/// 204. Moves no money. The amount may not exceed the shortfall at its date: what the months before its month still lack after the
/// contributions and earlier waivers (the current month's due is not a shortfall yet). A later backdated contribution makes the part no
/// longer needed void, so a waiver never creates a prepayment. Reversible. Repeats as for a deposit.
/// </summary>
/// <remarks>
/// Failures: 400 <c>validation.failed</c> (rule <c>NotEmptyValidator</c> at <c>note</c> when the reason is missing, <c>RouteFormat</c> at
/// <c>id</c>, <c>JsonFormat</c>), <c>money.amount_not_positive</c>; 404 <c>plan.not_found</c>, <c>settings.not_found</c>; 422
/// <c>plan.waiver_exceeds_shortfall</c>, <c>bucket.currency_mismatch</c>, <c>bucket.archived</c>, <c>entry.date_in_future</c>.
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client.</param>
/// <param name="Amount">Strictly positive, in the plan's currency.</param>
/// <param name="OccurredOn">The day of the waiver; not after today.</param>
/// <param name="Note">Required: the reason; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record WaiveShortfallRequest(
    Guid Id,
    Money Amount,
    DateOnly OccurredOn,
    string? Note = null,
    IReadOnlyList<string>? Tags = null);
