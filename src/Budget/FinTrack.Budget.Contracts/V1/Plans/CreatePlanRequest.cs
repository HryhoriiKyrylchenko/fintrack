using FinTrack.Shared.Kernel.Monetary;
using FinTrack.Shared.Kernel.Time;

namespace FinTrack.Budget.Contracts.V1.Plans;

/// <summary>
/// Body of <c>POST /api/v1/plans</c>: a new contribution plan for one bucket (ARCHITECTURE 4.5, plan 1b B7). Answers 204. The
/// plan's ID is <paramref name="Id"/>, the ID of its <c>PlanCreated</c> journal entry. It accrues <paramref name="Amount"/> in each
/// month from <paramref name="ValidFrom"/> to <paramref name="ValidTo"/> (or without an end); it may start in the past (catching up)
/// or later. Moves no money. Repeats as for a deposit (same ID and content: nothing written; other content:
/// <c>entry.id_reused</c>, 409).
/// </summary>
/// <remarks>
/// Failures: 400 <c>money.amount_not_positive</c>, <c>plan.months_invalid</c> (an end before the start), <c>validation.failed</c>
/// (rule <c>JsonFormat</c> for a month not written <c>yyyy-MM</c>); 404 <c>bucket.not_found</c>, <c>settings.not_found</c>;
/// 422 <c>bucket.system_bucket</c> (<c>Unallocated</c>), <c>bucket.archived</c>, <c>bucket.currency_mismatch</c>,
/// <c>entry.date_in_future</c>.
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client; also the plan's ID.</param>
/// <param name="BucketId">The bucket the plan saves into: a savings or investment bucket of the user.</param>
/// <param name="Amount">The monthly amount, strictly positive, in the bucket's currency.</param>
/// <param name="ValidFrom">The first month that accrues (<c>"2026-11"</c>).</param>
/// <param name="OccurredOn">The day the owner made the plan; not after today in the owner's time zone.</param>
/// <param name="ValidTo">The last month that accrues, or <c>null</c> for a plan without an end.</param>
/// <param name="Note">Optional; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record CreatePlanRequest(
    Guid Id,
    Guid BucketId,
    Money Amount,
    YearMonth ValidFrom,
    DateOnly OccurredOn,
    YearMonth? ValidTo = null,
    string? Note = null,
    IReadOnlyList<string>? Tags = null);
