using FinTrack.Shared.Kernel.Time;

namespace FinTrack.Budget.Contracts.V1.Plans;

/// <summary>
/// Body of <c>POST /api/v1/plans/{id}/pauses</c>: a pause of the plan from <paramref name="From"/> to <paramref name="To"/> (inclusive;
/// without <c>to</c>, until changed), plan 1b B10. Answers 204. The pause's ID is <paramref name="Id"/>. Paused months accrue nothing;
/// <c>Shift</c> moves the plan's end later by them, <c>Skip</c> keeps it. A pause may start in the current month or later: one that
/// would change what an earlier month accrued is refused (invariant 6). One-time deposits are never blocked. Repeats as for a deposit.
/// </summary>
/// <remarks>
/// Failures: 400 <c>plan.months_invalid</c> (<paramref name="To"/> before <paramref name="From"/>), <c>validation.failed</c> (rule
/// <c>RouteFormat</c> at <c>id</c>, or <c>JsonFormat</c>); 404 <c>plan.not_found</c>, <c>settings.not_found</c>; 422 <c>plan.ended</c>,
/// <c>plan.pause_overlaps</c> (another pause of the plan shares a month), <c>bucket.archived</c>, <c>entry.date_in_future</c>,
/// <c>plan.past_period_changed</c> (parameter <c>month</c>, <c>yyyy-MM</c>).
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client; also the pause's ID.</param>
/// <param name="From">The first paused month.</param>
/// <param name="Mode"><c>Shift</c> or <c>Skip</c>.</param>
/// <param name="OccurredOn">The day the owner made the pause; not after today.</param>
/// <param name="To">The last paused month, or <c>null</c> to pause until changed.</param>
/// <param name="Note">Optional; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record PausePlanRequest(
    Guid Id,
    YearMonth From,
    PauseMode Mode,
    DateOnly OccurredOn,
    YearMonth? To = null,
    string? Note = null,
    IReadOnlyList<string>? Tags = null);
