namespace FinTrack.Budget.Contracts.V1.Journal;

/// <summary>
/// Body of <c>POST /api/v1/journal/reversals</c>: cancels one earlier entry, which then counts as if it
/// never happened at its original date (plan 1a D3). Answers 204. An entry is reversed at most once; a
/// reversal cannot be reversed. Repeats as for <see cref="AddDepositRequest"/>.
/// </summary>
/// <remarks>
/// Failures: <c>entry.not_found</c> (404); <c>entry.not_reversible</c>, <c>entry.already_reversed</c>,
/// <c>bucket.archived</c> (the entry touches an archived bucket), <c>bucket.insufficient_funds</c> (the journal
/// without the entry would be below zero on some day, parameter <c>date</c>), <c>entry.date_in_future</c> (422).
/// </remarks>
/// <param name="Id">The reversal's ID, a version 7 UUID generated by the client.</param>
/// <param name="ReversedEntryId">The entry to cancel.</param>
/// <param name="OccurredOn">The day of the correction; not after today in the owner's time zone.</param>
/// <param name="Note">Optional, for example why; at most 500 characters.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record ReverseEntryRequest(Guid Id, Guid ReversedEntryId, DateOnly OccurredOn, string? Note = null, IReadOnlyList<string>? Tags = null);
