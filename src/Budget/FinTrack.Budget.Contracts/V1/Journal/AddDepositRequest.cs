using FinTrack.Shared.Kernel.Monetary;

namespace FinTrack.Budget.Contracts.V1.Journal;

/// <summary>
/// Body of <c>POST /api/v1/journal/deposits</c>: new money into one bucket. Answers 204. The client
/// generates <paramref name="Id"/>; repeating the request with the same ID and content changes
/// nothing, with other content it fails with <c>entry.id_reused</c> (409).
/// </summary>
/// <remarks>
/// The target is exactly one of <paramref name="BucketId"/> and <paramref name="Unallocated"/>
/// (otherwise <c>validation.failed</c>, rule <c>ExactlyOneTarget</c>). <c>Unallocated</c> of a currency
/// is created by the first deposit that needs it. Failures: <c>money.amount_not_positive</c> (400),
/// <c>bucket.not_found</c> (404), <c>bucket.archived</c>, <c>bucket.currency_mismatch</c>,
/// <c>entry.date_in_future</c> (422), <c>settings.not_found</c> (404, before first run).
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client.</param>
/// <param name="Amount">Strictly positive, in the target bucket's currency.</param>
/// <param name="OccurredOn">The business date; not after today in the owner's time zone.</param>
/// <param name="BucketId">The receiving bucket, or <c>null</c> when <paramref name="Unallocated"/> is set.</param>
/// <param name="Unallocated">The currency whose <c>Unallocated</c> bucket receives the money, or <c>null</c>.</param>
/// <param name="Note">Optional; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record AddDepositRequest(
    Guid Id,
    Money Amount,
    DateOnly OccurredOn,
    Guid? BucketId = null,
    Currency? Unallocated = null,
    string? Note = null,
    IReadOnlyList<string>? Tags = null);
