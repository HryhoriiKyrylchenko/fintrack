using FinTrack.Shared.Kernel.Monetary;

namespace FinTrack.Budget.Contracts.V1.Journal;

/// <summary>
/// Body of <c>POST /api/v1/journal/borrows</c>: money borrowed from a savings bucket with the obligation to return it (plan 1b B2).
/// Answers 204. Opens a loan whose ID is <paramref name="Id"/>. The destination is at most one of <paramref name="ToBucketId"/> and
/// <paramref name="ToUnallocated"/>; with neither, the money left the app. Never income. Repeats as for <see cref="AddDepositRequest"/>.
/// </summary>
/// <remarks>
/// Failures: 400 <c>validation.failed</c> (rule <c>AtMostOneTarget</c> at <c>toBucketId</c> when both are set),
/// <c>money.amount_not_positive</c>, <c>borrow.same_bucket</c> (the destination is the lender); 404 <c>bucket.not_found</c>;
/// 422 <c>bucket.system_bucket</c> (the lender is <c>Unallocated</c>), <c>bucket.borrow_not_allowed</c> (an investment lender),
/// <c>bucket.archived</c>, <c>bucket.currency_mismatch</c> (the principal or the destination not in the lender's currency),
/// <c>entry.date_in_future</c>, and <c>bucket.insufficient_funds</c> when the lender's available money would be below zero on any day
/// of its history (parameter <c>date</c>: the first such day).
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client; also the loan's ID.</param>
/// <param name="LenderBucketId">The savings bucket the money is borrowed from.</param>
/// <param name="Principal">Strictly positive, in the lender's currency.</param>
/// <param name="OccurredOn">The business date; not after today in the owner's time zone.</param>
/// <param name="ToBucketId">The destination bucket, or <c>null</c>.</param>
/// <param name="ToUnallocated">The currency of the destination <c>Unallocated</c> bucket, or <c>null</c>.</param>
/// <param name="Note">Optional; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record AddBorrowRequest(
    Guid Id,
    Guid LenderBucketId,
    Money Principal,
    DateOnly OccurredOn,
    Guid? ToBucketId = null,
    Currency? ToUnallocated = null,
    string? Note = null,
    IReadOnlyList<string>? Tags = null);
