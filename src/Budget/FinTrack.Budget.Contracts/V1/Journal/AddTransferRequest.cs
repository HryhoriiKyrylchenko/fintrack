using FinTrack.Shared.Kernel.Monetary;

namespace FinTrack.Budget.Contracts.V1.Journal;

/// <summary>
/// Body of <c>POST /api/v1/journal/transfers</c>: money moved between two different buckets, as one
/// entry (plan 1a D6). Answers 204. The amounts are the truth; the server derives and stores the rate.
/// Repeats as for <see cref="AddDepositRequest"/>.
/// </summary>
/// <remarks>
/// Each side is exactly one of a bucket ID and an <c>Unallocated</c> currency (otherwise
/// <c>validation.failed</c>, rule <c>ExactlyOneTarget</c>, at <c>fromBucketId</c> or <c>toBucketId</c>). In one
/// currency, <paramref name="ToAmount"/> must be exactly <paramref name="FromAmount"/> minus
/// <paramref name="Fee"/>. Failures (400): <c>transfer.same_bucket</c>, <c>transfer.fee_exceeds_amount</c>,
/// <c>transfer.amounts_inconsistent</c>, <c>money.amount_not_positive</c>, <c>bucket.currency_mismatch</c> (a fee
/// not in the source currency); (404) <c>bucket.not_found</c>; (422) <c>bucket.archived</c>,
/// <c>bucket.currency_mismatch</c> (an amount not in its bucket's currency), <c>bucket.insufficient_funds</c>
/// (parameter <c>date</c>), <c>entry.date_in_future</c>.
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client.</param>
/// <param name="FromAmount">Everything that leaves the source, fee included, in the source's currency.</param>
/// <param name="ToAmount">What arrives, in the destination's currency.</param>
/// <param name="OccurredOn">The business date; not after today in the owner's time zone.</param>
/// <param name="FromBucketId">The source bucket, or <c>null</c> when <paramref name="FromUnallocated"/> is set.</param>
/// <param name="FromUnallocated">The currency of the source <c>Unallocated</c> bucket, or <c>null</c>.</param>
/// <param name="ToBucketId">The destination bucket, or <c>null</c> when <paramref name="ToUnallocated"/> is set.</param>
/// <param name="ToUnallocated">The currency of the destination <c>Unallocated</c> bucket, or <c>null</c>.</param>
/// <param name="Fee">Optional; part of <paramref name="FromAmount"/>, in the source's currency.</param>
/// <param name="Note">Optional; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
/// <param name="PlanId">
/// Optional (plan 1b B9): the contribution plan of the destination that this transfer pays with <paramref name="ToAmount"/>; still never
/// income. Failures: <c>plan.not_found</c> (404), <c>plan.bucket_mismatch</c> (422, the plan saves into another bucket).
/// </param>
public sealed record AddTransferRequest(
    Guid Id,
    Money FromAmount,
    Money ToAmount,
    DateOnly OccurredOn,
    Guid? FromBucketId = null,
    Currency? FromUnallocated = null,
    Guid? ToBucketId = null,
    Currency? ToUnallocated = null,
    Money? Fee = null,
    string? Note = null,
    IReadOnlyList<string>? Tags = null,
    Guid? PlanId = null);
