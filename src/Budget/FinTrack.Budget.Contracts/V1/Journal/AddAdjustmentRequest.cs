using FinTrack.Shared.Kernel.Monetary;

namespace FinTrack.Budget.Contracts.V1.Journal;

/// <summary>
/// Body of <c>POST /api/v1/journal/adjustments</c>: a manual correction of one bucket with a reason (plan 1b B14).
/// Answers 204. Never income; raises or lowers the bucket's <c>netContributed</c> and is exempt from its limit.
/// Allowed on any active bucket, <c>Unallocated</c> and investment buckets included. The target (exactly one of
/// <paramref name="BucketId"/> and <paramref name="Unallocated"/>) and the repeat rules are those of
/// <see cref="AddDepositRequest"/>.
/// </summary>
/// <remarks>
/// Additional failures: a missing or empty note is 400 <c>validation.failed</c> (field <c>note</c>, rule
/// <c>NotEmptyValidator</c>); a decrease that would leave a savings bucket below zero on any day of its history is
/// 422 <c>bucket.insufficient_funds</c> (parameter <c>date</c>: the first such day).
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client.</param>
/// <param name="Amount">Strictly positive, in the bucket's currency.</param>
/// <param name="Direction">Whether the adjustment raises or lowers the bucket.</param>
/// <param name="OccurredOn">The business date; not after today in the owner's time zone.</param>
/// <param name="Note">Required: the reason; at most 500 characters, line breaks allowed.</param>
/// <param name="BucketId">The bucket, or <c>null</c> when <paramref name="Unallocated"/> is set.</param>
/// <param name="Unallocated">The currency of the <c>Unallocated</c> bucket, or <c>null</c>.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record AddAdjustmentRequest(
    Guid Id,
    Money Amount,
    AdjustmentDirection Direction,
    DateOnly OccurredOn,
    string? Note = null,
    Guid? BucketId = null,
    Currency? Unallocated = null,
    IReadOnlyList<string>? Tags = null);
