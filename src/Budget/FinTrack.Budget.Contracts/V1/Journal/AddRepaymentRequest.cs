using FinTrack.Shared.Kernel.Monetary;

namespace FinTrack.Budget.Contracts.V1.Journal;

/// <summary>
/// Body of <c>POST /api/v1/journal/repayments</c>: loan principal paid back to its lender (plan 1b B2, B4). Answers 204. The source is
/// at most one of <paramref name="FromBucketId"/> and <paramref name="FromUnallocated"/>; with neither, it is new money from outside.
/// Never income. Repeats as for <see cref="AddDepositRequest"/>.
/// </summary>
/// <remarks>
/// Failures: 400 <c>validation.failed</c> (rule <c>AtMostOneTarget</c> at <c>fromBucketId</c> when both are set),
/// <c>money.amount_not_positive</c>; 404 <c>loan.not_found</c> (no effective borrow has this ID), <c>bucket.not_found</c>;
/// 422 <c>loan.closed</c>, <c>repayment.from_lender</c>, <c>bucket.archived</c>, <c>bucket.currency_mismatch</c> (not in the lender's
/// currency), <c>entry.date_in_future</c>, <c>loan.repayment_exceeds_outstanding</c> when the repayment would exceed the loan's
/// outstanding principal on any day, also when dated before the borrow, and <c>bucket.insufficient_funds</c> when the source would be
/// below zero on any day (parameter <c>date</c> for both: the first such day).
/// </remarks>
/// <param name="Id">The entry's ID, a version 7 UUID generated by the client.</param>
/// <param name="LoanId">The loan: the ID of the borrow that opened it.</param>
/// <param name="Amount">Strictly positive, in the lender's currency; at most the outstanding principal.</param>
/// <param name="OccurredOn">The business date; not after today in the owner's time zone.</param>
/// <param name="FromBucketId">The source bucket, or <c>null</c>.</param>
/// <param name="FromUnallocated">The currency of the source <c>Unallocated</c> bucket, or <c>null</c>.</param>
/// <param name="Note">Optional; at most 500 characters, line breaks allowed.</param>
/// <param name="Tags">Optional; at most 10 distinct tags of up to 30 characters.</param>
public sealed record AddRepaymentRequest(
    Guid Id,
    Guid LoanId,
    Money Amount,
    DateOnly OccurredOn,
    Guid? FromBucketId = null,
    Currency? FromUnallocated = null,
    string? Note = null,
    IReadOnlyList<string>? Tags = null);
